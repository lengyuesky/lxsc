const assert = require('node:assert/strict')
const path = require('node:path')
module.exports = async ({ check, url, login, search, playSearch, createPlaylist, selectPlaylistUI, artifacts }) => {
  await check('六项功能：歌单入队、换版本历史与恢复', async page => {
    const original = ['tr-wy-1', 'tr-wy-2']
    const playlist = await createPlaylist(page, url, '可恢复的换版本', original)
    await selectPlaylistUI(page, playlist.id)
    await page.locator('[data-track-index="0"] [data-track-action=play]').click()
    await page.waitForFunction(() => webPlayer.status === 'playing')
    await page.locator('[data-track-index="1"] [data-track-action=queue]').click()
    await page.locator('#queueAddLast').click()
    assert.equal(await page.evaluate(() => webPlayer.queue.length), 3)
    assert.equal(await page.evaluate(() => webPlayer.track.id), original[0])
    await page.locator('[data-track-index="0"] [data-track-action=repair]').click()
    await page.locator('#repairForm button').click()
    await page.locator('[data-repair-use="0"]').click()
    await page.locator('#saveTracksButton').click()
    await page.waitForFunction(() => !playlistState.tracksDirty)
    const changed = await (await page.request.get(url + '/api/app/playlists/' + playlist.id)).json()
    assert.notDeepEqual(changed.tracks.map(t => t.id), original)
    await page.locator('#playlistHistoryOpen').click()
    await page.locator('[data-history-id]').first().click()
    await page.waitForFunction(() => !document.querySelector('#restorePlaylistHistory').disabled)
    await page.screenshot({ path: path.join(artifacts, 'song-history.png'), fullPage: true })
    await page.locator('#restorePlaylistHistory').click()
    assert.deepEqual(await page.evaluate(() => playlistState.draftTracks.map(t => t.id)), original)
    assert.equal(await page.evaluate(() => playlistState.tracksDirty), true)
    await page.locator('#saveTracksButton').click()
    await page.waitForFunction(() => !playlistState.tracksDirty)
    assert.deepEqual((await (await page.request.get(url + '/api/app/playlists/' + playlist.id)).json()).tracks.map(t => t.id), original)
    assert.equal((await page.request.get(url + '/api/app/playlists/pl-bob-public/history')).status(), 403)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  }, { viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, colorScheme: 'dark' })
  await check('六项功能：智能歌单自然月与另存', async page => {
    const user = (await (await page.request.get(url + '/api/auth/me')).json()).user
    const stats = await (await page.request.get(url + '/api/app/listening/stats?days=30&scope=me')).json()
    const now = Date.now(), day = new Date(now + 8 * 3600000).toISOString().slice(0, 10)
    const startedAt = Math.max(now - 60000, stats.enabledAt)
    const response = await page.request.post(url + '/api/app/listening/progress', { data: { userId: user.id, sessionId: 'six-feature-' + now, trackId: 'tr-wy-1', startedAt, days: { [day]: Math.min(1000, now - startedAt) } } })
    assert.equal(response.status(), 200)
    await page.locator('#tab-search details').locator('summary').click()
    await page.locator('#smartTracksForm [name=kind]').selectOption('month')
    await page.locator('#smartTracksForm button').click()
    await page.waitForFunction(() => songSearchState.smartKind === 'month' && songSearchState.tracks.length > 0)
    assert.match(await page.locator('#songSearchStatus').textContent(), /本月最爱/)
    page.once('dialog', dialog => dialog.accept('本月最爱验收'))
    const saved = page.waitForResponse(response => response.url().endsWith('/api/app/playlists') && response.request().method() === 'POST')
    await page.locator('#smartSave').click()
    assert.equal((await saved).status(), 200)
    const detail = await (await saved).json()
    assert.equal(detail.public, false)
    assert.ok(detail.tracks.length > 0)
    await search(page, '其他查询')
    assert.equal(await page.locator('#smartSave').isDisabled(), true)
  })
  await check('六项功能：音源健康展示、系统媒体信息与下一首入队', async page => {
    await search(page, '媒体信息'); await playSearch(page)
    const title = await page.locator('#playerTitle').textContent()
    assert.equal(await page.evaluate(() => navigator.mediaSession.metadata.title), title)
    await page.locator('[data-song-action=queue][data-song-index="1"]').click()
    await page.locator('#queueAddNext').click()
    assert.equal(await page.evaluate(() => webPlayer.queue[webPlayer.index + 1].id), 'tr-wy-2')
    await page.locator('#logoutButton').click(); await page.locator('#login:not(.hidden)').waitFor(); await login(page, url, 'admin')
    await page.route('**/api/admin/sources', route => route.fulfill({ json: [{ id: 1, name: '健康面板验收', enabled: true, priority: 1, status: { state: 'ready', platforms: {}, health: { samples: 10, success: 8, averageMs: 123, downgrades: 2, errors: { timeout: 1, script: 1 } } } }] }))
    await page.locator('nav [data-tab=sources]').click()
    await page.locator('#sourceList').getByText(/成功率 80%/).waitFor()
    assert.match(await page.locator('#sourceList').textContent(), /降级 2 次/)
    assert.match(await page.locator('#sourceList').textContent(), /超时 1/)
    await page.screenshot({ path: path.join(artifacts, 'source-health.png'), fullPage: true, animations: 'disabled' })
  })
}
